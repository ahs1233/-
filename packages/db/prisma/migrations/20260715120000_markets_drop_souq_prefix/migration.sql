-- إزالة بادئة «سوگ » من أسماء الأسواق الافتراضيّة: شعار التطبيق (بجانب الاسم)
-- هو من يحمل هويّة السوگ، فلا حاجة لتكرار الكلمة على كلّ بوّابة. نحذفها فقط من
-- الصفوف التي ما زالت تحمل الاسم الافتراضيّ (WHERE nameAr = القديم) كي لا نطمس
-- تسميةً خصّصها الأدمن. تعمل عبر migrate deploy الحرِج.

UPDATE "Market" AS m SET "nameAr" = v.newname, "updatedAt" = now()
FROM (VALUES
  ('stores',      'سوگ {gov}',            '{gov}'),
  ('electronics', 'سوگ {gov} الإلكتروني', '{gov} الإلكتروني'),
  ('food',        'سوگ الطعام',           'الطعام'),
  ('realestate',  'سوگ العقار',           'العقار'),
  ('cars',        'سوگ السيارات',         'السيارات'),
  ('jobs',        'سوگ الوظائف',          'الوظائف'),
  ('services',    'سوگ الخدمات',          'الخدمات'),
  ('travel',      'سوگ السفر',            'السفر'),
  ('health',      'سوگ الصحة',            'الصحة'),
  ('education',   'سوگ التعليم',          'التعليم')
) AS v(slug, oldname, newname)
WHERE m."slug" = v.slug AND m."nameAr" = v.oldname;
