// Generates the C engine for the JS test from the live lastgtg engine, the same way
// ../handoff/build_lastgtg.py builds lastgtg_C_1_1.pine: exact replacements, each found once.
//   node indicators/lastgtg/review_1_1/js/build-c.mjs
// Writes zone-engine-c.mjs (c_breaking.pinefrag in JS, no strong-body acceptance) and
// measure-c.mjs (live measure.mjs pointed at it). Import paths gain one level (js/ is one
// directory deeper than live/). Refuses to run when the live files differ from what it expects.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const live = join(here, '../../live');

const OLD_STRONG = `      const strongBody = ge(Math.abs(c - o), P.dispBodyK * atr) && (gt(dir, 0) ? gt(c, o) : lt(c, o));
      if (strongBody) acceptBreak(lv, bi, ev);
`;
const NEW_STRONG = `      // [C] the first close only arms BREAKING, regardless of body size.
`;

const OLD_BREAKING = `    if (beyond && gt(bi, lv.stateChartBar)) {
      lv.breakCloses += 1;
      if (ge(lv.breakCloses, 2)) acceptBreak(lv, bi, ev);
    } else if (back) {
      lv.state = lv.breakFromFlip ? ST.FLIP : ST.ACTIVE;
      ev.log.push({ k: 'failedAcceptance', key: lv.key, dir, toState: lv.state, armed: !!lv.navArmed }); // [MEASURE] E3
      lv.tests += 1; lv.evidence = Math.min(3, lv.evidence + 0.5); lv.lastTestChartBar = bi;
      lv.navArmed = false;
    } else if (ge(bi - lv.stateChartBar, P.BREAK_WINDOW)) {
      lv.state = lv.breakFromFlip ? ST.FLIP : ST.ACTIVE;
      ev.log.push({ k: 'breakExpired', key: lv.key, dir, toState: lv.state }); // [MEASURE]
      lv.navArmed = false;
    }
`;
// c_breaking.pinefrag: window [start, start + BREAK_WINDOW), expiry first, then a return to the
// old side, then consecutive beyond-buffer closes (a close that is not beyond resets the count).
const NEW_BREAKING = `    if (ge(bi - lv.stateChartBar, P.BREAK_WINDOW)) { // [C] expiry takes precedence; no acceptance at offset 3
      lv.state = lv.breakFromFlip ? ST.FLIP : ST.ACTIVE;
      ev.log.push({ k: 'breakExpired', key: lv.key, dir, toState: lv.state }); // [MEASURE]
      lv.breakCloses = 0; // [C]
      lv.navArmed = false;
    } else if (back) {
      lv.state = lv.breakFromFlip ? ST.FLIP : ST.ACTIVE;
      ev.log.push({ k: 'failedAcceptance', key: lv.key, dir, toState: lv.state, armed: !!lv.navArmed }); // [MEASURE] E3
      lv.tests += 1; lv.evidence = Math.min(3, lv.evidence + 0.5); lv.lastTestChartBar = bi;
      lv.breakCloses = 0; // [C]
      lv.navArmed = false;
    } else if (gt(bi, lv.stateChartBar)) { // [C] each call is the next confirmed chart bar
      lv.breakCloses = beyond ? lv.breakCloses + 1 : 0;
      if (ge(lv.breakCloses, 2)) acceptBreak(lv, bi, ev);
    }
`;

function once(text, from, to, label) {
  const n = text.split(from).length - 1;
  if (n !== 1) throw new Error(`${label}: expected exactly one match in the live file, found ${n}`);
  return text.replace(from, () => to);
}

const sha = (s) => createHash('sha256').update(s).digest('hex');
const engineSrc = readFileSync(join(live, 'zone-engine.mjs'), 'utf8');
const measureSrc = readFileSync(join(live, 'measure.mjs'), 'utf8');

let eng = once(engineSrc, OLD_STRONG, NEW_STRONG, 'strong body');
eng = once(eng, OLD_BREAKING, NEW_BREAKING, 'BREAKING branch');
eng = once(eng, "from '../../gtg-strategy-lab/engine/pine-cmp.mjs';", "from '../../../gtg-strategy-lab/engine/pine-cmp.mjs';", 'pine-cmp import');
eng = `// GENERATED by review_1_1/js/build-c.mjs from live/zone-engine.mjs (sha256 ${sha(engineSrc)}) — do not edit.
// lastgtg C (review 1.1): c_breaking.pinefrag in JS, marked [C]; nothing else differs.
` + eng;

let mea = measureSrc;
mea = once(mea, "} from './zone-engine.mjs';", "} from './zone-engine-c.mjs';", 'engine import');
mea = mea.replaceAll("from '../../gtg-strategy-lab/", "from '../../../gtg-strategy-lab/");
if (mea.includes("from '../../gtg-strategy-lab/")) throw new Error('measure import paths not rewritten');
mea = `// GENERATED by review_1_1/js/build-c.mjs from live/measure.mjs (sha256 ${sha(measureSrc)}) — do not edit.
// The live runner pointed at the C engine (./zone-engine-c.mjs).
` + mea;

writeFileSync(join(here, 'zone-engine-c.mjs'), eng);
writeFileSync(join(here, 'measure-c.mjs'), mea);
console.log('zone-engine-c.mjs', sha(eng));
console.log('measure-c.mjs', sha(mea));
